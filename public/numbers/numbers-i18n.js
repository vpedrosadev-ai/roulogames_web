export function createNumbersTranslator(getLanguage) {
  return function translate(key, values = {}) {
    const table = NUMBERS_TRANSLATIONS[getLanguage()] || NUMBERS_TRANSLATIONS.es;
    const template = table[key] ?? NUMBERS_TRANSLATIONS.es[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
    ));
  };
}
